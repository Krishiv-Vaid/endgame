// Texel tuner for the endgame HCE.
//
//   texel <data.txt>... [--epochs N] [--lr X] [--lambda L] [--out FILE] [--threads N]
//
// Data lines: "<fen> | <white score> | <white result>" (as written by the
// engine's `datagen` command). The HCE is linear in its parameters, so each
// position is stored once as a sparse list of feature counts and the
// tapered eval is recomputed in floating point from the current weights.
// Loss: MSE between sigmoid(K * eval) and
//   target = lambda * result + (1 - lambda) * sigmoid(K * search_score).
// K is fitted first (with the starting weights), then Adam runs full-batch.

#include <algorithm>
#include <atomic>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <thread>
#include <vector>

#include "eval_hce.h"
#include "init.h"
#include "position.h"

using namespace endgame;

namespace {

struct Feature {
    std::uint16_t index;
    std::int16_t coef;
};

struct Sample {
    std::uint32_t begin, end;  // into the feature array
    float phase_mg;            // phase / 24
    float result;
    float score;               // search score, white view
};

struct Dataset {
    std::vector<Feature> features;
    std::vector<Sample> samples;
};

int g_threads = 8;

template <typename F>
void parallel_for(std::size_t n, F&& fn) {
    std::vector<std::thread> pool;
    const std::size_t chunk = (n + g_threads - 1) / g_threads;
    for (int t = 0; t < g_threads; ++t) {
        std::size_t lo = t * chunk, hi = std::min(n, lo + chunk);
        if (lo >= hi) break;
        pool.emplace_back([&fn, t, lo, hi]() { fn(t, lo, hi); });
    }
    for (auto& th : pool) th.join();
}

bool load(const std::string& path, Dataset& ds, std::size_t max_positions) {
    std::ifstream in(path);
    if (!in) return false;
    std::string line;
    hce::Trace tr;
    Position pos;
    while (std::getline(in, line) && ds.samples.size() < max_positions) {
        auto a = line.find('|'), b = line.rfind('|');
        if (a == std::string::npos || a == b) continue;
        std::string fen = line.substr(0, a);
        float score = std::strtof(line.substr(a + 1, b - a - 1).c_str(), nullptr);
        float result = std::strtof(line.substr(b + 1).c_str(), nullptr);
        if (!pos.set(fen)) continue;
        evaluate_trace(pos, tr);
        Sample s;
        s.begin = std::uint32_t(ds.features.size());
        for (int i = 0; i < hce::PARAM_COUNT; ++i)
            if (tr.coef[i]) ds.features.push_back({std::uint16_t(i), tr.coef[i]});
        s.end = std::uint32_t(ds.features.size());
        s.phase_mg = float(tr.phase) / PHASE_MAX;
        s.result = result;
        s.score = score;
        ds.samples.push_back(s);
    }
    return true;
}

struct Weights {
    std::vector<double> mg, eg;
};

inline double eval_sample(const Dataset& ds, const Sample& s, const Weights& w) {
    double mg = 0, eg = 0;
    for (std::uint32_t i = s.begin; i < s.end; ++i) {
        const Feature& f = ds.features[i];
        mg += f.coef * w.mg[f.index];
        eg += f.coef * w.eg[f.index];
    }
    return mg * s.phase_mg + eg * (1.0 - s.phase_mg);
}

inline double sigmoid(double x) { return 1.0 / (1.0 + std::exp(-x)); }

double loss(const Dataset& ds, const Weights& w, double k, double lambda) {
    std::vector<double> partial(g_threads, 0.0);
    parallel_for(ds.samples.size(), [&](int t, std::size_t lo, std::size_t hi) {
        double acc = 0;
        for (std::size_t i = lo; i < hi; ++i) {
            const Sample& s = ds.samples[i];
            double target = lambda * s.result + (1 - lambda) * sigmoid(k * s.score);
            double d = sigmoid(k * eval_sample(ds, s, w)) - target;
            acc += d * d;
        }
        partial[t] = acc;
    });
    double total = 0;
    for (double p : partial) total += p;
    return total / double(ds.samples.size());
}

double fit_k(const Dataset& ds, const Weights& w, double lambda) {
    // Golden-section search on K in [0.0005, 0.02] (eval in centipawns).
    double lo = 0.0005, hi = 0.02;
    const double g = (std::sqrt(5.0) - 1) / 2;
    double a = hi - g * (hi - lo), b = lo + g * (hi - lo);
    double la = loss(ds, w, a, lambda), lb = loss(ds, w, b, lambda);
    for (int it = 0; it < 40; ++it) {
        if (la < lb) {
            hi = b, b = a, lb = la, a = hi - g * (hi - lo), la = loss(ds, w, a, lambda);
        } else {
            lo = a, a = b, la = lb, b = lo + g * (hi - lo), lb = loss(ds, w, b, lambda);
        }
    }
    return (lo + hi) / 2;
}

void write_params(const std::string& path, const Weights& w) {
    std::ofstream out(path);
    out << "// Generated by tools/texel. Do not edit by hand.\n"
           "// One {mg, eg} pair per hce::ParamIndex entry.\n"
           "#pragma once\n"
           "constexpr int TUNED_PARAM_COUNT = "
        << hce::PARAM_COUNT << ";\nconstexpr endgame::S TUNED_PARAMS[TUNED_PARAM_COUNT] = {\n";
    char name[64];
    for (int i = 0; i < hce::PARAM_COUNT; ++i) {
        out << "    {" << std::lround(w.mg[i]) << ", " << std::lround(w.eg[i]) << "},  // "
            << hce::param_name(i, name, sizeof(name)) << '\n';
    }
    out << "};\n";
}

}  // namespace

int main(int argc, char** argv) {
    init_all();
    std::vector<std::string> files;
    int epochs = 2000;
    double lr = 1.0, lambda = 1.0;
    std::size_t max_positions = SIZE_MAX;
    std::string out_path = "src/hce_params.inc";
    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        auto next = [&]() { return std::string(i + 1 < argc ? argv[++i] : ""); };
        if (a == "--epochs") epochs = std::stoi(next());
        else if (a == "--lr") lr = std::stod(next());
        else if (a == "--lambda") lambda = std::stod(next());
        else if (a == "--out") out_path = next();
        else if (a == "--threads") g_threads = std::max(1, std::stoi(next()));
        else if (a == "--max") max_positions = std::stoull(next());
        else files.push_back(a);
    }
    if (files.empty()) {
        std::cerr << "usage: texel <data.txt>... [--epochs N] [--lr X] [--lambda L] [--out FILE]\n";
        return 1;
    }

    Dataset ds;
    for (const auto& f : files) {
        if (!load(f, ds, max_positions)) std::cerr << "cannot read " << f << '\n';
        std::cout << "loaded " << f << ": " << ds.samples.size() << " positions total" << std::endl;
    }
    if (ds.samples.empty()) return 1;

    Weights w;
    w.mg.resize(hce::PARAM_COUNT);
    w.eg.resize(hce::PARAM_COUNT);
    for (int i = 0; i < hce::PARAM_COUNT; ++i) w.mg[i] = hce::params[i].mg, w.eg[i] = hce::params[i].eg;

    const double k = fit_k(ds, w, lambda);
    std::printf("K = %.6f, initial loss %.6f\n", k, loss(ds, w, k, lambda));

    // Adam, full batch.
    const int n = hce::PARAM_COUNT;
    std::vector<double> m1(2 * n, 0), m2(2 * n, 0);
    const double b1 = 0.9, b2 = 0.999, eps = 1e-8;
    for (int epoch = 1; epoch <= epochs; ++epoch) {
        std::vector<std::vector<double>> grads(g_threads, std::vector<double>(2 * n, 0.0));
        parallel_for(ds.samples.size(), [&](int t, std::size_t lo, std::size_t hi) {
            auto& g = grads[t];
            for (std::size_t i = lo; i < hi; ++i) {
                const Sample& s = ds.samples[i];
                double target = lambda * s.result + (1 - lambda) * sigmoid(k * s.score);
                double p = sigmoid(k * eval_sample(ds, s, w));
                double d = 2 * (p - target) * p * (1 - p) * k;
                for (std::uint32_t j = s.begin; j < s.end; ++j) {
                    const Feature& f = ds.features[j];
                    g[f.index] += d * f.coef * s.phase_mg;
                    g[n + f.index] += d * f.coef * (1 - s.phase_mg);
                }
            }
        });
        const double scale = 1.0 / double(ds.samples.size());
        for (int i = 0; i < 2 * n; ++i) {
            double g = 0;
            for (auto& tg : grads) g += tg[i];
            g *= scale;
            m1[i] = b1 * m1[i] + (1 - b1) * g;
            m2[i] = b2 * m2[i] + (1 - b2) * g * g;
            double mh = m1[i] / (1 - std::pow(b1, epoch)), vh = m2[i] / (1 - std::pow(b2, epoch));
            double step = lr * mh / (std::sqrt(vh) + eps);
            if (i < n) w.mg[i] -= step;
            else w.eg[i - n] -= step;
        }
        if (epoch % 50 == 0 || epoch == epochs) {
            std::printf("epoch %d loss %.6f\n", epoch, loss(ds, w, k, lambda));
            std::fflush(stdout);
            write_params(out_path, w);
        }
    }
    write_params(out_path, w);
    std::cout << "wrote " << out_path << std::endl;
    return 0;
}
